#!/bin/sh
# ─────────────────────────────────────────────────────────────────────────
# StudyMate · lab 判分入口骨架（固定叫 check.sh）
#
# 出题角色照抄这一份，**框架一个字都不用改**：要填的是任务（`任务单.md`）、作答格
# （`作答/`）、探针（`探针/`）与断言（`断言.sh`）——**只填题目与断言**。
#
# 跑手只跑一条命令：题库里那道 `kind: 交付物` 题的「证据」字段，写 `sh check.sh`。
#
# 这个脚本只做三件事，一件都不多：
#   1. **读参数**：谁都不给也行——不给就用本脚本所在目录，以及它下面的 作答/、探针/；
#   2. **跑断言**：把三个目录原样递给 `断言.sh`，它的输出直接透传（不截、不改、不加工）；
#   3. **如实转述**：把这一次的参数与退出码印成事实，再把那个退出码原样交回去。
#
# **退出码没有第二套码表**：本脚本不判任何东西，`断言.sh` 退出什么就交回什么。
# 非零不是判决，只是「这一次的退出码是多少」这条事实，跑手照记（判分契约见
# `<root>/preset/skills/layered-practice/SKILL.md` 第六节）。
#
# 参数（都可选）：$1 任务目录（默认本脚本所在目录）、$2 作答目录（默认 $1/作答）、
#                $3 探针目录（默认 $1/探针）
# 两个跑法（同一个入口，差别只在盘上的状态）：
#   干净态：cd <任务目录> && sh check.sh
#   作答态：参考解拷进任务目录之后再跑一次（或把 $2 指向 solutions/<NNNN>-<主题>/作答）
# 出题角色交件前跑 `sh 自检.sh`：它在干净目录里把这两个跑法各重跑一遍。
# ─────────────────────────────────────────────────────────────────────────
set -u

SELF=$(dirname "$0")
TASK=${1:-$SELF}
cd "$TASK" || exit          # 进不去就把 cd 自己那个退出码原样交出去（不编一个）
TASK=$PWD
ANSWERS=${2:-$TASK/作答}
PROBES=${3:-$TASK/探针}

printf '── check.sh · 事实 ──\n'
printf '任务目录：%s\n' "$TASK"
printf '作答目录：%s\n' "$ANSWERS"
printf '探针目录：%s\n' "$PROBES"
printf 'cwd：%s\n' "$PWD"
printf '断言：%s\n' "$TASK/断言.sh"

sh "$TASK/断言.sh" "$TASK" "$ANSWERS" "$PROBES"
CODE=$?

printf 'check.sh 退出码：%d\n' "$CODE"
exit "$CODE"
