#!/bin/sh
# ─────────────────────────────────────────────────────────────────────────
# StudyMate · lab 骨架自检：在干净目录里整套重跑两态
#
# 出题角色交件之前跑一次。它自己**不摆盘、不跑 check.sh**——那两件事各有一个运行入口：
#
#   `sh 干净态.sh`   任务留白、参考解仍在 `solutions/` 里 → 断言读不到那一格，退出码非零
#   `sh 作答态.sh`   把参考解的作答摆进临时副本再跑 → 退出码归零
#
# 这里只按顺序调用这两个入口，并把它们的退出码原样转述：
# 自检自己的退出码 = **最后一次**（作答态）那一次的，原样（没有第二套码表）。
#
# 用法：sh 自检.sh
# 变量名一律 ASCII：`sh` 认不得中文变量名（打印出来的标签仍是中文）。
# ─────────────────────────────────────────────────────────────────────────
set -u

ROOT=$(dirname "$0")
cd "$ROOT" || exit
ROOT=$PWD

sh "$ROOT/干净态.sh"
sh "$ROOT/作答态.sh"
exit
